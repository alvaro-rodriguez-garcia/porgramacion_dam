public class Ejercicio3 {
    public static void main(String[] args) {
        int operador1 = 24;
        int operador2 = 7;

        System.out.println("suma " + (operador1 + operador2));
        System.out.println("resta " + (operador1 - operador2));
        System.out.println("multiplicacion " + (operador1 * operador2));
        System.out.println("division " + (operador1 / operador2));
        System.out.println("resto " + (operador1 % operador2));
        System.out.println("division real " + ((double) operador1 / operador2));
        System.out.println("resto real " + ((double) operador1 % operador2));
    }
}
